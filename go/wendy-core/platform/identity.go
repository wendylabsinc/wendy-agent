package platform

import (
	"context"
	"io"
	"strings"
)

// HTTPHeaders preserves repeated HTTP header values. Names are compared without
// case by Get; hosts validate names and values when adapting to native networking.
type HTTPHeaders map[string][]string

// Get returns the first value for a header name, ignoring case.
func (h HTTPHeaders) Get(name string) string {
	for key, values := range h {
		if strings.EqualFold(key, name) && len(values) > 0 {
			return values[0]
		}
	}
	return ""
}

// Set replaces a header's values, removing any differently cased spelling.
func (h HTTPHeaders) Set(name, value string) {
	for key := range h {
		if strings.EqualFold(key, name) {
			delete(h, key)
		}
	}
	h[name] = []string{value}
}

// HTTPRequest carries only HTTP data, without a Go network client or TLS types.
// The host borrows the immutable request until Do returns.
type HTTPRequest struct {
	Method  string
	URL     string
	Headers HTTPHeaders
	Body    []byte
}

// HTTPResponse transfers ownership of its body and headers to the caller. Core
// bounds reads and closes Body. Hosts must not reuse the returned buffers.
type HTTPResponse struct {
	StatusCode int
	Headers    HTTPHeaders
	Body       io.ReadCloser
}

// HTTPTransport sends requests using host networking and TLS. The host honors
// ctx cancellation/deadlines until Body is closed. It must not retry exchanges
// or forward Authorization/DPoP headers across origins. Implementations must be
// safe for concurrent use and keep credentials out of logs. Core has no default
// network implementation and does not depend on Go's net/http or crypto/tls.
type HTTPTransport interface {
	Do(ctx context.Context, request HTTPRequest) (*HTTPResponse, error)
}

// SignatureVerifier verifies exact JWS signing bytes against a public JWK. The
// host implements the named algorithm (ES256 or ML-DSA-65). It returns an error
// for invalid signatures, unsupported algorithms, malformed keys or cancellation.
// Core validates claims only after successful verification.
type SignatureVerifier interface {
	VerifySignature(ctx context.Context, jwk map[string]string, message, signature []byte) error
}

// IdentityKey adds host-side PKCS#10 creation and certificate key binding to a
// Signer. Private key bytes stay in the host, including for a secondary Lite key.
type IdentityKey interface {
	Signer
	// CertificateRequest creates a PEM PKCS#10 request for subject with this key.
	CertificateRequest(ctx context.Context, subject string) ([]byte, error)
	// CheckCertificate parses a leaf-first PEM chain and refuses a leaf for a
	// different key. It returns normalized PEM and the sole tenant SPIFFE URI.
	// The host owns certificate parsing and cryptographic checks.
	CheckCertificate(ctx context.Context, chain []byte) (CertificateIdentity, error)
}

// CertificateIdentity contains public certificate material checked by the host.
// Core additionally validates tenant, principal kind and subject.
type CertificateIdentity struct {
	CertificatePEM string
	ChainPEM       string
	PrincipalURI   string
}

// Entropy supplies unpredictable bytes from the host's secure random generator.
// Returned bytes belong to the caller and must contain exactly size bytes.
// Hosts honor cancellation and do not include generated bytes in errors/logs.
type Entropy interface {
	RandomBytes(ctx context.Context, size int) ([]byte, error)
}
