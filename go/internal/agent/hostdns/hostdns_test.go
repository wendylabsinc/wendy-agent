// TestWaitConfigured_ProceedsOnTimeout is the property that keeps this from
// bricking an offline device: a deliberately network-less host must still start
// its apps, so the wait is bounded and returning false means "proceed".
func TestWaitConfigured_ProceedsOnTimeout(t *testing.T) {
	orig := readFile
	t.Cleanup(func() { readFile = orig })
	readFile = func(string) ([]byte, error) { return []byte("search .\n"), nil }

	var waited, timedOut bool
	start := time.Now()
	ok := WaitConfigured(context.Background(), 40*time.Millisecond,
		func() { waited = true }, func() { timedOut = true })
	if ok {
		t.Fatal("want false when no resolver ever appears")
	}
	if !waited || !timedOut {
		t.Errorf("both callbacks should fire; waited=%v timedOut=%v", waited, timedOut)
	}
	if elapsed := time.Since(start); elapsed > 3*time.Second {
		t.Errorf("waited %v, far longer than the timeout", elapsed)
	}
}

// A resolver appearing mid-wait must be noticed, and must not report a timeout.
func TestWaitConfigured_NoticesALateResolver(t *testing.T) {
	orig := readFile
	t.Cleanup(func() { readFile = orig })
	var calls int
	readFile = func(string) ([]byte, error) {
		calls++
		if calls > 2 {
			return []byte("nameserver 192.168.0.1\n"), nil
		}
		return []byte("search .\n"), nil
	}

	var timedOut bool
	if !WaitConfigured(context.Background(), 5*time.Second, nil, func() { timedOut = true }) {
		t.Fatal("want true once a resolver appears")
	}
	if timedOut {
		t.Error("must not report a timeout when a resolver was found")
	}
}

// An already-configured host must not wait at all, so a healthy boot is not
// delayed and no misleading "waiting" line is logged.
func TestWaitConfigured_DoesNotWaitWhenAlreadyConfigured(t *testing.T) {
	orig := readFile
	t.Cleanup(func() { readFile = orig })
	readFile = func(string) ([]byte, error) { return []byte("nameserver 10.0.0.1\n"), nil }

	var waited bool
	if !WaitConfigured(context.Background(), time.Second, func() { waited = true }, nil) {
		t.Fatal("want true for an already-configured host")
	}
	if waited {
		t.Error("must not announce waiting when nothing is waited for")
	}
}

// Cancellation must return promptly rather than holding shutdown open.
func TestWaitConfigured_RespectsCancellation(t *testing.T) {
	orig := readFile
	t.Cleanup(func() { readFile = orig })
	readFile = func(string) ([]byte, error) { return []byte("search .\n"), nil }

	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if WaitConfigured(ctx, time.Minute, nil, nil) {
		t.Error("want false when the context is already cancelled")
	}
}

