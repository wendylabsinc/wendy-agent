// TestHasNameserver_RealWorldBrokenFiles uses the exact contents seen on hosts
// where this went wrong. Both look like a populated, readable config and name
// no resolver, which is why an existence check passes and DNS still fails.
func TestHasNameserver_RealWorldBrokenFiles(t *testing.T) {
	// systemd-resolved before it has learned an upstream. Observed verbatim on a
	// dev container that could not reach github.com while its host could.
	resolved := `# This is /run/systemd/resolve/stub-resolv.conf managed by man:systemd-resolved(8).
# Do not edit.

# No DNS servers known.
search .
`
	if HasNameserver(resolved) {
		t.Error("a resolved stub with no upstream must not count as configured")
	}
	// NetworkManager before DHCP completes.
	if HasNameserver("# Generated by NetworkManager\nsearch localdomain\n") {
		t.Error("a search-only config must not count as configured")
	}
	if HasNameserver("") {
		t.Error("an empty file must not count as configured")
	}
}

func TestHasNameserver_RejectsValuelessAndCommented(t *testing.T) {
	for _, in := range []string{"nameserver\n", "nameserver   \n", "# nameserver 8.8.8.8\n", "; nameserver 1.1.1.1\n"} {
		if HasNameserver(in) {
			t.Errorf("must not count as configured: %q", in)
		}
	}
}

func TestHasNameserver_AcceptsWorkingConfigs(t *testing.T) {
	for name, in := range map[string]string{
		"plain":           "nameserver 192.168.0.1\n",
		"search first":    "search localdomain\nnameserver 192.168.0.1\n",
		"tab separated":   "nameserver\t192.168.0.1\n",
		"leading space":   "   nameserver 192.168.0.1\n",
		"resolved stub":   "nameserver 127.0.0.53\noptions edns0 trust-ad\n",
		"ipv6":            "nameserver fd00::1\n",
		"after a comment": "# managed by NetworkManager\nnameserver 10.0.0.1\n",
		"mixed case":      "Nameserver 10.0.0.1\n",
	} {
		if !HasNameserver(in) {
			t.Errorf("%s: want configured for %q", name, in)
		}
	}
}

