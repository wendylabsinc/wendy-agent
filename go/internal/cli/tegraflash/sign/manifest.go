package sign

import (
	"encoding/xml"
	"fmt"
	"io"
)

// SignEntry describes one signable region in a tegrasign_v3 file-list XML.
// Name is the filename (e.g. "br_bct_BR.bct"), Offset and Length are the
// byte range within the file that covers the signed section, and HashFile
// is the path where the AES-CMAC hash output is written.
type SignEntry struct {
	Name     string
	Offset   int64
	Length   int64
	HashFile string
}

// sbkNode is the <sbk> child element of a <file> node.
type sbkNode struct {
	XMLName     xml.Name `xml:"sbk"`
	Encrypt     string   `xml:"encrypt,attr"`
	Sign        string   `xml:"sign,attr"`
	EncryptFile string   `xml:"encrypt_file,attr"`
	Hash        string   `xml:"hash,attr"`
}

// pkcNode is the <pkc> child element carrying the digest type for the
// asymmetric-key path. In zerosbk mode no real signature is computed, but
// the node is still emitted with digest_type="sha512".
type pkcNode struct {
	XMLName    xml.Name `xml:"pkc"`
	Signature  string   `xml:"signature,attr"`
	SignedFile string   `xml:"signed_file,attr"`
	DigestType string   `xml:"digest_type,attr"`
}

// fileNode corresponds to one <file> element in the file_list XML.
type fileNode struct {
	XMLName xml.Name `xml:"file"`
	Name    string   `xml:"name,attr"`
	Offset  int64    `xml:"offset,attr"`
	Length  int64    `xml:"length,attr"`
	Type    string   `xml:"type,attr"`
	SBK     sbkNode
	PKC     pkcNode
}

// WriteSignedManifest writes the tegrasign_v3 signed-manifest XML to w.
// The root element is <file_list mode="sbk"> (tegrasign_v3 always uses "sbk"
// as the XML tag for both "sbk" and "zerosbk" modes, per util line 916).
// Each entry produces one <file type="bct"> node containing <sbk> and <pkc>
// children, matching the format documented in tegrabct_v2-br-bct-format.md
// section 5.
func WriteSignedManifest(w io.Writer, entries []SignEntry) error {
	if _, err := fmt.Fprintln(w, `<?xml version="1.0"?>`); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(w, `<!-- Auto generated by tegrasign -->`); err != nil {
		return err
	}
	if _, err := fmt.Fprintln(w, `<file_list mode="sbk">`); err != nil {
		return err
	}

	enc := xml.NewEncoder(w)
	enc.Indent("  ", "  ")

	for _, e := range entries {
		// Derive side-file names from HashFile / Name if not specified.
		hashFile := e.HashFile
		if hashFile == "" {
			hashFile = e.Name + ".hash"
		}
		encryptFile := e.Name + ".encrypt"
		sigFile := e.Name + ".sig"
		signedFile := e.Name + ".signed"

		node := fileNode{
			Name:   e.Name,
			Offset: e.Offset,
			Length: e.Length,
			Type:   "bct",
			SBK: sbkNode{
				Encrypt:     "1",
				Sign:        "1",
				EncryptFile: encryptFile,
				Hash:        hashFile,
			},
			PKC: pkcNode{
				Signature:  sigFile,
				SignedFile: signedFile,
				DigestType: "sha512",
			},
		}
		if err := enc.Encode(node); err != nil {
			return err
		}
	}

	if err := enc.Flush(); err != nil {
		return err
	}

	if _, err := fmt.Fprintln(w, "\n</file_list>"); err != nil {
		return err
	}
	return nil
}
