package buildspec

import (
	"encoding/json"
	"fmt"
	"strconv"
	"strings"
)

func renderDockerfile(plan Plan) (string, error) {
	var output strings.Builder
	output.WriteString("# Generated by Wendy Build Spec v1. DO NOT EDIT.\n")
	output.WriteString("# plan: " + plan.PlanID + "\n")
	for _, step := range plan.Steps {
		switch step.Kind {
		case "from":
			fmt.Fprintf(&output, "\nFROM %s AS %s\n", step.Image, step.Stage)
		case "env":
			if err := validateEnvironmentStep(step); err != nil {
				return "", err
			}
			fmt.Fprintf(&output, "ENV %s=%s\n", step.Name, strconv.Quote(step.Value))
		case "run-shell":
			renderShell(&output, step.ID, step.Script)
		case "workdir":
			fmt.Fprintf(&output, "WORKDIR %s\n", step.Directory)
		case "copy-inputs":
			renderCopy(&output, "", step.Sources, step.Destination)
		case "run":
			encoded, err := json.Marshal(step.Command)
			if err != nil {
				return "", fmt.Errorf("encode %s: %w", step.ID, err)
			}
			fmt.Fprintf(&output, "RUN %s\n", encoded)
		case "copy-artifact":
			renderCopy(&output, step.From, step.Sources, step.Destination)
		case "entrypoint":
			encoded, err := json.Marshal(step.Command)
			if err != nil {
				return "", fmt.Errorf("encode %s: %w", step.ID, err)
			}
			fmt.Fprintf(&output, "ENTRYPOINT %s\n", encoded)
		default:
			return "", fmt.Errorf("unsupported build plan step kind %q", step.Kind)
		}
	}
	return output.String(), nil
}

func renderCopy(output *strings.Builder, from string, sources []string, destination string) {
	if len(sources) == 1 && sources[0] == "." && from == "" {
		fmt.Fprintf(output, "COPY . %s\n", destination)
		return
	}
	values := append([]string(nil), sources...)
	values = append(values, destination)
	encoded, _ := json.Marshal(values)
	if from == "" {
		fmt.Fprintf(output, "COPY %s\n", encoded)
		return
	}
	fmt.Fprintf(output, "COPY --from=%s %s\n", from, encoded)
}

func renderShell(output *strings.Builder, id, script string) {
	if !strings.ContainsAny(script, "\r\n") {
		fmt.Fprintf(output, "RUN %s\n", script)
		return
	}
	delimiter := "WENDY_" + strings.NewReplacer(".", "_", "-", "_").Replace(strings.ToUpper(id))
	for strings.Contains(script, delimiter) {
		delimiter += "_END"
	}
	fmt.Fprintf(output, "RUN <<'%s'\n%s\n%s\n", delimiter, strings.TrimRight(script, "\r\n"), delimiter)
}
